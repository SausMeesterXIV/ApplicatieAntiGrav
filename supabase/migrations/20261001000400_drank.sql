begin;

-- ---------------------------------------------------------------------
-- 1. Prijs per streep
-- ---------------------------------------------------------------------
alter table public.consumpties add column if not exists prijs numeric(6,2);

update public.consumpties c
set prijs = d.prijs
from public.dranken d
where d.id = c.drank_id and c.prijs is null;

create or replace function public.consumptie_zet_prijs()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.prijs is null then
    select prijs into new.prijs from dranken where id = new.drank_id;
  end if;
  return new;
end;
$$;

drop trigger if exists consumptie_zet_prijs on public.consumpties;
create trigger consumptie_zet_prijs
  before insert on public.consumpties
  for each row execute function public.consumptie_zet_prijs();

-- ---------------------------------------------------------------------
-- 2. Voorraad volgt de strepen automatisch
-- ---------------------------------------------------------------------
create or replace function public.consumptie_voorraad()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then
    update dranken set huidige_voorraad = huidige_voorraad + old.aantal where id = old.drank_id;
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    update dranken set huidige_voorraad = huidige_voorraad - new.aantal where id = new.drank_id;
  end if;
  return null;
end;
$$;

drop trigger if exists consumptie_voorraad on public.consumpties;
create trigger consumptie_voorraad
  after insert or delete or update of aantal, drank_id on public.consumpties
  for each row execute function public.consumptie_voorraad();

create table if not exists public.voorraad_correcties (
  id uuid primary key default gen_random_uuid(),
  drank_id uuid not null references public.dranken(id) on delete cascade,
  oude_voorraad integer not null,
  nieuwe_voorraad integer not null,
  notitie text,
  door uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.voorraad_correcties enable row level security;
create policy "drankteam ziet correcties" on public.voorraad_correcties for select using (public.heeft_recht('drank_beheren'));

-- Na een manuele telling: zet de voorraad en log de correctie
create or replace function public.corrigeer_voorraad(p_drank_id uuid, p_nieuwe_voorraad integer, p_notitie text default null)
returns void language plpgsql security definer set search_path = public as $$
declare v_oud integer;
begin
  if not public.heeft_recht('drank_beheren') then
    raise exception 'Enkel Drankteam mag de voorraad corrigeren';
  end if;
  select huidige_voorraad into v_oud from dranken where id = p_drank_id for update;
  if not found then raise exception 'Onbekende drank'; end if;
  update dranken set huidige_voorraad = p_nieuwe_voorraad where id = p_drank_id;
  insert into voorraad_correcties (drank_id, oude_voorraad, nieuwe_voorraad, notitie, door)
  values (p_drank_id, v_oud, p_nieuwe_voorraad, p_notitie, auth.uid());
end;
$$;

