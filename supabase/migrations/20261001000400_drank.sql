-- Drank en strepen (CLAUDE.md: Drank en strepen)
--  - prijs per streep wordt bewaard op het moment van strepen
--  - voorraad per drank daalt automatisch bij elke streep; Drankteam corrigeert na telling
--  - Drankteam sluit een periode af: per leider een echte factuur met gestructureerde mededeling
--  - één berekening voor saldo, preview en factuur: periode_overzicht()
--  - ranking van de huidige periode, zichtbaar voor alle leiding (enkel totalen)
-- Vereist: 20261001000100_rollen_en_rechten.sql en 20261001000200_rls_policies.sql
